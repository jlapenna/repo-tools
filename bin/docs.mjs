#!/usr/bin/env node
import { execFileSync } from 'node:child_process';
import { existsSync, readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { parse } from 'yaml';

const read = (file) => readFileSync(file, 'utf8');
const cell = (value) => String(value).replaceAll('|', '\\|').replaceAll('\n', ' ');

export function repositoryFiles(root) {
  return [...new Set(execFileSync('git', ['ls-files', '-z', '--cached', '--others', '--exclude-standard', '--exclude=node_modules/', '--exclude=.venv/'], { cwd: root, encoding: 'utf8' }).split('\0').filter(Boolean))].sort();
}

export function skillMetadata(text, file) {
  const match = /^---\r?\n([\s\S]*?)\r?\n---(?:\r?\n|$)/.exec(text);
  if (!match) throw new Error(`${file}: missing YAML frontmatter`);
  const data = parse(match[1], { uniqueKeys: true });
  for (const key of ['name', 'description']) {
    if (typeof data?.[key] !== 'string' || !data[key].trim()) throw new Error(`${file}: ${key} must be a nonempty string`);
  }
  for (const key of ['disable-model-invocation', 'user-invocable']) {
    if (key in data && typeof data[key] !== 'boolean') throw new Error(`${file}: ${key} must be boolean`);
  }
  return data;
}

export function inventory(root, files = repositoryFiles(root)) {
  const rows = { Commands: [], Skills: [], 'Explicit Nx targets': [], 'Deployment targets': [] };
  for (const file of files) {
    const full = path.join(root, file);
    if (!existsSync(full)) continue; // tracked deletion
    if (file === 'package.json') {
      const pkg = JSON.parse(read(full));
      const bins = typeof pkg.bin === 'string' ? { [pkg.name]: pkg.bin } : pkg.bin ?? {};
      for (const [name, script] of Object.entries(bins)) rows.Commands.push([name, script]);
    } else if (path.basename(file) === 'SKILL.md') {
      const skill = skillMetadata(read(full), file);
      rows.Skills.push([skill.name, file]);
    } else if (path.basename(file) === 'project.json') {
      const project = JSON.parse(read(full));
      const pkgFile = path.join(path.dirname(full), 'package.json');
      const name = project.name ?? (existsSync(pkgFile) ? JSON.parse(read(pkgFile)).name : undefined);
      if (!name) continue; // Do not guess Nx-inferred names or targets.
      for (const target of Object.keys(project.targets ?? {})) rows['Explicit Nx targets'].push([`${name}:${target}`, file]);
    } else if (/^apps\/[^/]+\/infra\/deployment\.yaml$/.test(file)) {
      const manifest = parse(read(full), { uniqueKeys: true });
      for (const target of Object.keys(manifest?.apps ?? {})) rows['Deployment targets'].push([`${file.split('/')[1]}/${target}`, file]);
    }
  }
  return rows;
}

export function renderInventory(root, output, files) {
  let text = '<!-- Generated by repo-docs generate. Do not edit by hand. -->\n# Repository interfaces\n\nThis inventory comes from package, skill, Nx project, and deployment manifests.\nNx-inferred targets are intentionally not listed. Runtime status is not inferred.\n';
  for (const [section, rows] of Object.entries(inventory(root, files))) {
    if (!rows.length) continue;
    text += `\n## ${section}\n\n| Name | Source |\n| --- | --- |\n`;
    rows.sort(([a, x], [b, y]) => a.localeCompare(b, 'en') || x.localeCompare(y, 'en'));
    for (const [name, file] of rows) {
      const link = path.relative(path.dirname(output), file).split(path.sep).map(encodeURIComponent).join('/');
      text += `| ${cell(name)} | [${cell(file)}](${link}) |\n`;
    }
  }
  return text;
}

export function checkMarkdown(root, file) {
  const errors = [];
  const full = path.resolve(root, file);
  if (!existsSync(full)) return errors;
  const original = read(full);
  if (path.basename(file) === 'SKILL.md') {
    try { skillMetadata(original, file); } catch (error) { errors.push(error.message); }
  }
  // Validate literal local file links, not examples, web routes, or heading slugs.
  const text = original.replace(/(^|\n)(`{3,}|~{3,})[^\n]*\n[\s\S]*?\n\2[^\n]*(?=\n|$)/g, '\n').replace(/`[^`\n]*`/g, '');
  const targets = [...text.matchAll(/!?\[[^\]\n]*\]\(\s*(<[^>]+>|[^\s)]+)(?:\s+["'][^\n]*?["'])?\s*\)/g), ...text.matchAll(/^\s{0,3}\[[^\]\n]+\]:\s*(<[^>]+>|\S+)/gm)];
  for (const match of targets) {
    let target = match[1].replace(/^<|>$/g, '').split(/[?#]/)[0];
    if (!target || /^(?:[a-z][a-z\d+.-]*:|\/)/i.test(target) || /[<>{}*$]/.test(target)) continue;
    try { target = decodeURIComponent(target); } catch { errors.push(`${file}: invalid URL encoding: ${target}`); continue; }
    if (!existsSync(path.resolve(path.dirname(full), target))) errors.push(`${file}: missing link target: ${target}`);
  }
  return errors;
}

export function main(args) {
  const mode = args.shift();
  if (!['check', 'generate'].includes(mode)) throw new Error('Usage: repo-docs check|generate [--root DIR] [--output FILE] [--files FILE ...]');
  let root = process.cwd();
  let output;
  let selected;
  while (args.length) {
    const arg = args.shift();
    if (arg === '--root' && args.length) root = path.resolve(args.shift());
    else if (arg === '--output' && args.length) output = args.shift();
    else if (arg === '--files') { selected = args.splice(0); break; }
    else throw new Error(`Unknown or incomplete option: ${arg}`);
  }
  if (output && (path.isAbsolute(output) || path.relative(root, path.resolve(root, output)).startsWith('..'))) throw new Error('Output must be inside the repository');
  const files = repositoryFiles(root);
  if (mode === 'generate') {
    if (!output) throw new Error('generate requires --output FILE');
    const content = renderInventory(root, output, files);
    mkdirSync(path.dirname(path.join(root, output)), { recursive: true });
    writeFileSync(path.join(root, output), content);
    return;
  }
  const errors = [];
  if (output && (!existsSync(path.join(root, output)) || read(path.join(root, output)) !== renderInventory(root, output, files))) errors.push(`${output}: stale inventory; run repo-docs generate --output ${output}`);
  for (const file of selected ?? files) {
    if (/\.mdx?$/.test(file)) errors.push(...checkMarkdown(root, file));
  }
  if (errors.length) throw new Error(errors.join('\n'));
  console.log('Documentation contracts passed (literal local file links, skill frontmatter, requested inventory).');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { main(process.argv.slice(2)); } catch (error) { console.error(error.message); process.exitCode = 1; }
}
